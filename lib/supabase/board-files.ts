import type { SupabaseClient } from "@supabase/supabase-js";
import {
  formatOfMime,
  identifyFile,
  normalizeLinkUrl,
  titleFromFileName,
  titleFromUrl,
  type FileFormat,
  type FileRejection,
} from "@/lib/files/file-helpers";

/** The private Storage bucket every board file lives in. */
export const BOARD_FILES_BUCKET = "board-files";

const TABLE = "board_files";
const COLUMNS = "id, board_id, name, size_bytes, kind, mime_type, url, storage_path, created_at";
// What the table had before `20261028150000_board_files_more_types.sql`.
const LEGACY_COLUMNS = "id, board_id, name, size_bytes, storage_path, created_at";

export type BoardFile = {
  id: string;
  boardId: string;
  name: string;
  sizeBytes: number;
  kind: "file" | "link";
  /** What a viewer needs to know; `link` for a web link. */
  format: FileFormat;
  mimeType: string | null;
  /** A link's address; `null` for a stored file. */
  url: string | null;
  /** `<board id>/<file id>.<ext>` — generated by Postgres, never sent by the client; `null` for a link. */
  storagePath: string | null;
  createdAt: string;
};

/** A file whose bytes are in Storage (everything but a link) — what a viewer is given. */
export type StoredBoardFile = BoardFile & { storagePath: string };

export function isStoredFile(file: BoardFile): file is StoredBoardFile {
  return file.kind === "file" && file.storagePath !== null;
}

type BoardFileRow = {
  id: string;
  board_id: string;
  name: string;
  size_bytes: number;
  storage_path: string | null;
  created_at: string;
  // Absent until the second migration has been applied.
  kind?: "file" | "link";
  mime_type?: string | null;
  url?: string | null;
};

function rowToBoardFile(row: BoardFileRow): BoardFile {
  const kind = row.kind ?? "file";
  // A row from before the second migration is a PDF by definition.
  const mimeType = kind === "link" ? null : (row.mime_type ?? "application/pdf");
  return {
    id: row.id,
    boardId: row.board_id,
    name: row.name,
    sizeBytes: row.size_bytes,
    kind,
    format: kind === "link" ? "link" : (formatOfMime(mimeType) ?? "pdf"),
    mimeType,
    url: row.url ?? null,
    storagePath: row.storage_path,
    createdAt: row.created_at,
  };
}

/**
 * Which shape the `board_files` table has: `legacy` is the first migration
 * only (PDFs), `current` has the second (more types, links). The sidebar
 * keeps working on `legacy` and says what to apply to unlock the rest.
 */
export type FilesSchema = "current" | "legacy";

/**
 * The `board_files` table or the `board-files` bucket doesn't exist — the
 * migration that creates them hasn't been applied to this database yet.
 * Separate from a plain failure because "Try again" can never fix it: the
 * sidebar says what is missing instead of offering a retry loop.
 */
export class FilesNotSetUpError extends Error {
  constructor() {
    super("File storage hasn't been set up on this database yet");
    this.name = "FilesNotSetUpError";
  }
}

/**
 * The database refused a type of item (or a link) it doesn't know yet:
 * `20261028150000_board_files_more_types.sql` hasn't been applied.
 */
export class FileTypeNotEnabledError extends Error {
  constructor() {
    super("This database doesn't accept this kind of file yet");
    this.name = "FileTypeNotEnabledError";
  }
}

/** The database's ten-items-per-board limit rejected an insert. */
export class FileLimitError extends Error {
  constructor() {
    super("A board can hold at most 10 files");
    this.name = "FileLimitError";
  }
}

/** The file failed `identifyFile` before any request went out. */
export class FileRejectedError extends Error {
  constructor(readonly reason: FileRejection) {
    super(`File rejected: ${reason}`);
    this.name = "FileRejectedError";
  }
}

/** What was typed as a link isn't an address we'll keep. */
export class InvalidLinkError extends Error {
  constructor() {
    super("That isn't a web address");
    this.name = "InvalidLinkError";
  }
}

type ErrorLike = { code?: string; message?: string; statusCode?: string | number } | null | undefined;

/**
 * PostgREST answers a missing table with `PGRST205` (it looks the table up
 * in its schema cache) or, on older versions, Postgres's own `42P01`.
 * Storage answers a missing bucket with a 404 "Bucket not found".
 */
function isNotSetUp(error: ErrorLike): boolean {
  if (!error) return false;
  if (error.code === "PGRST205" || error.code === "42P01") return true;
  return /bucket not found/i.test(error.message ?? "");
}

/** A column the second migration adds isn't there (`42703`, or `PGRST204` on a write). */
function isMissingColumn(error: ErrorLike): boolean {
  if (!error) return false;
  return error.code === "42703" || error.code === "PGRST204";
}

/** The signed-in user's items for one board, oldest first (sidebar order). */
export async function listBoardFiles(
  supabase: SupabaseClient,
  boardId: string,
): Promise<{ files: BoardFile[]; schema: FilesSchema }> {
  const query = (columns: string) =>
    supabase.from(TABLE).select(columns).eq("board_id", boardId).order("created_at", { ascending: true });

  let schema: FilesSchema = "current";
  let { data, error } = await query(COLUMNS);
  if (isMissingColumn(error)) {
    schema = "legacy";
    ({ data, error } = await query(LEGACY_COLUMNS));
  }
  if (error) {
    if (isNotSetUp(error)) throw new FilesNotSetUpError();
    throw error;
  }
  return { files: (data as unknown as BoardFileRow[]).map(rowToBoardFile), schema };
}

/** Maps what an insert can fail with to something the sidebar can explain. */
function insertFailure(error: NonNullable<ErrorLike>): Error {
  if (error.code === "P0001") return new FileLimitError();
  if (isNotSetUp(error)) return new FilesNotSetUpError();
  // The first migration's checks reject any type but PDF with 23514; a
  // missing column is the same situation (the second migration isn't there).
  if (error.code === "23514" || isMissingColumn(error)) return new FileTypeNotEnabledError();
  return error as Error;
}

/**
 * Adds a file to a board: works out what it really is, inserts its row (the
 * database enforces the ten-item limit there), then uploads the bytes. In
 * that order on purpose — Storage only accepts an upload at a path that
 * already has a row, so the limit is checked before any bandwidth is spent,
 * and a failed upload just deletes the row again instead of leaving an item
 * in the sidebar that can't be opened.
 */
export async function addBoardFile(
  supabase: SupabaseClient,
  boardId: string,
  file: File,
  id: string = crypto.randomUUID(),
): Promise<BoardFile> {
  const identified = await identifyFile(file);
  if (!identified.ok) throw new FileRejectedError(identified.reason);

  const { data, error } = await supabase
    .from(TABLE)
    .insert({
      id,
      board_id: boardId,
      name: titleFromFileName(file.name),
      size_bytes: file.size,
      mime_type: identified.mime,
    })
    // Only the columns every version of the table has: PostgREST fails the
    // whole insert if asked to return one that doesn't exist yet, and a stored
    // file's kind, type and (lack of) url are known here anyway. This is what
    // keeps adding a PDF working before the second migration is applied.
    .select(LEGACY_COLUMNS)
    .single();
  if (error) throw insertFailure(error);
  const created = rowToBoardFile({
    ...(data as unknown as BoardFileRow),
    kind: "file",
    mime_type: identified.mime,
    url: null,
  });

  // For a file upload the Storage client sends the file's *own* type and
  // ignores the `contentType` option, and the bucket checks it against its
  // allowed types. Browsers report an empty type for things like `.epub` and
  // `.md`, so the bytes are re-wrapped with the type we detected. (A `File`
  // wrapping a `File` doesn't copy the data.)
  const body = file.type === identified.mime ? file : new File([file], file.name, { type: identified.mime });
  const { error: uploadError } = await supabase.storage
    .from(BOARD_FILES_BUCKET)
    .upload(created.storagePath!, body, { contentType: identified.mime, upsert: false });
  if (uploadError) {
    await supabase.from(TABLE).delete().eq("id", created.id);
    if (isNotSetUp(uploadError)) throw new FilesNotSetUpError();
    // The bucket's allowed types come from the second migration too.
    if (/mime type .* not supported|unsupported mime/i.test(uploadError.message ?? "")) throw new FileTypeNotEnabledError();
    throw uploadError;
  }
  return created;
}

/** Saves a web link in a board's sidebar. Nothing is stored; the row is the link. */
export async function addBoardLink(
  supabase: SupabaseClient,
  boardId: string,
  address: string,
  title?: string,
  id: string = crypto.randomUUID(),
): Promise<BoardFile> {
  const url = normalizeLinkUrl(address);
  if (!url) throw new InvalidLinkError();

  const { data, error } = await supabase
    .from(TABLE)
    .insert({
      id,
      board_id: boardId,
      kind: "link",
      name: (title?.trim() || titleFromUrl(url)).slice(0, 200),
      url,
      mime_type: null,
      size_bytes: 0,
    })
    .select(COLUMNS)
    .single();
  if (error) throw insertFailure(error);
  return rowToBoardFile(data as unknown as BoardFileRow);
}

export async function renameBoardFile(supabase: SupabaseClient, fileId: string, name: string): Promise<void> {
  const { error } = await supabase.from(TABLE).update({ name }).eq("id", fileId);
  if (error) throw error;
}

/**
 * Removes the stored bytes first, then the row (a link has no bytes). If
 * the second step fails the item stays in the sidebar and removing it again
 * just works (deleting an object that's already gone is not an error); the
 * other order could leave stored bytes with no row, which nothing in the UI
 * can reach.
 */
export async function removeBoardFile(supabase: SupabaseClient, file: BoardFile): Promise<void> {
  if (file.storagePath) {
    const { error: storageError } = await supabase.storage.from(BOARD_FILES_BUCKET).remove([file.storagePath]);
    if (storageError) throw storageError;
  }
  const { error } = await supabase.from(TABLE).delete().eq("id", file.id);
  if (error) throw error;
}

/**
 * A short-lived link to a file's bytes, for a viewer to read from. The
 * bucket is private, so this is the only way to read a file; the link is
 * only handed out if the caller's session passes the Storage read policy.
 */
export async function createBoardFileUrl(supabase: SupabaseClient, storagePath: string): Promise<string> {
  const { data, error } = await supabase.storage.from(BOARD_FILES_BUCKET).createSignedUrl(storagePath, 60 * 60);
  if (error || !data) throw error ?? new Error("No signed URL returned");
  return data.signedUrl;
}

/**
 * Deleting a board deletes its `board_files` rows by cascade, but Storage
 * objects can't be reached from SQL, so the bytes would be left behind. This
 * clears them first. Best effort and never throws: a board must stay
 * deletable even where file storage isn't set up, or Storage is down —
 * the worst case is some unreachable bytes, not a board that can't go.
 */
export async function removeStoredFilesForBoard(supabase: SupabaseClient, boardId: string): Promise<void> {
  try {
    const { data, error } = await supabase.from(TABLE).select("storage_path").eq("board_id", boardId);
    if (error || !data) return;
    const paths = (data as { storage_path: string | null }[])
      .map((row) => row.storage_path)
      .filter((path): path is string => Boolean(path));
    if (paths.length === 0) return;
    await supabase.storage.from(BOARD_FILES_BUCKET).remove(paths);
  } catch (error) {
    console.warn("Couldn't clear a deleted board's stored files:", error);
  }
}
